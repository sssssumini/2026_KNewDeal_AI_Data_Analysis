# [문제]
# 아래 판정 규칙을 함수로 구현하세요.
#
# Q1. 열화 과정이 물리적으로 존재하는가?
# - 손상형태가 "과부하 파단" 또는 "이물"이면
#   → "물리적 돌발"
#
# Q2. P-F 간격이 리드타임보다 긴가?
# - PF간격_일 <= 리드타임이면
#   → "간격 부족형"
#
# Q3. 해당 신호가 데이터에 저장되는가?
# - 데이터저장여부가 "Y"가 아니면
#   → "측정 부재형"
#
# 위 조건에 모두 해당하지 않으면
#   → "예측 가능형"
#
# 함수 이름은 자유롭게 정해도 됩니다.
# 함수는 '한 행'과 '리드타임'을 입력받아
# 판정 문자열을 반환하도록 작성해 보세요.


def check(row, lead_time):

    if row["손상형태"] in ["과부하 파단", "이물"]:
        status = "물리적 돌발"
    elif row["PF간격_일"] <= lead_time:
        status = "간격 부족형"
    elif row["데이터저장여부"] != "Y":
        status = "측정 부재형"
    else:
        status = "예측 가능형"

    return status


